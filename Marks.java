public class Marks{
	public static void main(String[]args){
		int Marks;
		Marks = 40;
		if(Marks>=90)
		{
			System.out.println("A+");
		}
		else if(Marks>80)
		{
			System.out.println("A");
		}
		else if(Marks>70)
		{
			System.out.println("B");
		}
		else
		{
			System.out.println("Fail");
		}
	}
}

	